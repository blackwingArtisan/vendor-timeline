/**
 * Bryntum Gantt is served as its own script, not bundled. Its 6 MB obfuscated module made a
 * Turbopack build peak at about 14 GB of RAM, past the 8 GB a Render build gets.
 *
 * next.config.ts calls this on every dev, build and start:
 * - switch on: copy the installed gantt.umd.js to public/sponsor/, and write a shim that
 *   re-exports `globalThis.bryntum.gantt`, so `import { X } from "@bryntum/gantt"` (ours and the
 *   React wrapper's) costs nothing to bundle. sponsor-load.ts adds the script tag first.
 * - switch off: delete both, so no sponsor file can be served.
 * Both outputs are git-ignored and rebuilt from node_modules, so they follow the installed version.
 */
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

export const SPONSOR_PUBLIC_DIR = path.join("public", "sponsor");
export const SPONSOR_SHIM = path.join(".sponsor", "gantt-shim.mjs");

/** Every name gantt.module.js exports, read from its single trailing `export{...}`. */
export function moduleExports(source: string): string[] {
  const start = source.lastIndexOf("export{");
  const end = source.indexOf("}", start);
  if (start < 0 || end < 0) throw new Error("gantt.module.js: no export list found");
  return source
    .slice(start + "export{".length, end)
    .split(",")
    .map((part) => part.split(" as ").pop()!.trim())
    .filter(Boolean);
}

export function shimSource(names: string[]): string {
  const lines = [
    "// Generated by scripts/sponsor-files.ts. The Gantt itself is public/sponsor/gantt.umd.js.",
    "const g = globalThis.bryntum?.gantt;",
    'if (!g && typeof window !== "undefined") throw new Error("Bryntum Gantt script is not loaded: see sponsor-load.ts");',
    "const all = g ?? {};",
  ];
  for (const name of names) lines.push(name === "default" ? "export default all.default;" : `export const ${name} = all.${name};`);
  return lines.join("\n") + "\n";
}

function writeIfChanged(file: string, data: string | Buffer) {
  if (fs.existsSync(file) && Buffer.compare(fs.readFileSync(file), Buffer.from(data)) === 0) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
}

export function prepareSponsorFiles(on: boolean, root = process.cwd()) {
  const publicDir = path.join(root, SPONSOR_PUBLIC_DIR);
  const shim = path.join(root, SPONSOR_SHIM);
  if (!on) {
    fs.rmSync(publicDir, { recursive: true, force: true });
    fs.rmSync(path.dirname(shim), { recursive: true, force: true });
    return;
  }
  const pkg = path.dirname(createRequire(path.join(root, "package.json")).resolve("@bryntum/gantt/package.json"));
  writeIfChanged(path.join(publicDir, "gantt.umd.js"), fs.readFileSync(path.join(pkg, "gantt.umd.js")));
  writeIfChanged(shim, shimSource(moduleExports(fs.readFileSync(path.join(pkg, "gantt.module.js"), "utf8"))));
}
